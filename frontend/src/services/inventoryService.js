import api from './api'

const routes = { 'Stock In': 'StockIn', 'Stock Out': 'StockOut', 'Stock Adjustment': 'StockAdjustment', 'Stock Ledger': 'StockLedger', Purchases: 'Purchases' }
const options = () => {
  const token = localStorage.getItem('agriman_access_token') || sessionStorage.getItem('agriman_access_token')
  const baseURL = import.meta.env.DEV ? '' : (import.meta.env.VITE_INVENTORY_API_URL || api.defaults.baseURL)
  return { baseURL, ...(token ? { headers: { Authorization: `Bearer ${token}` } } : {}) }
}
export function unwrapList(value) {
  const list = Array.isArray(value) ? value : value?.data?.items ?? value?.data ?? value?.items
  if (!Array.isArray(list)) throw new Error('The inventory API returned an unexpected list response.')
  return list
}
export async function loadInventory(screen) {
  const [response, inventoryResponse] = await Promise.all([
    api.get(`/api/${routes[screen]}`, options()), api.get('/api/Inventory', options()),
  ])
  const inventory = unwrapList(inventoryResponse.data)
  const records = unwrapList(response.data).map((row) => {
    const item = inventory.find((entry) => entry.inventoryId === row.inventoryId)
    const type = row.movementType
    return {
      'Transaction No': row.stockMovementId, 'Adjustment No': row.stockMovementId,
      Date: row.movementDate?.slice(0, 10) ?? '', Product: row.itemName ?? item?.itemName ?? '',
      Quantity: Math.abs(row.quantity ?? 0), Unit: row.unit ?? item?.unit ?? '',
      'Source / Supplier': item?.supplier ?? '', 'Reference No': row.referenceNumber ?? '',
      Remarks: row.description ?? '', Reason: row.description ?? '',
      'Adjustment Type': row.newQuantity < row.previousQuantity ? 'Decrease' : 'Increase',
      'Transaction Type': ({ StockIn: 'Stock In', StockOut: 'Stock Out', Adjustment: 'Adjustment' })[type] ?? type ?? '',
      'Stock In': type === 'StockIn' ? row.quantity : 0, 'Stock Out': type === 'StockOut' ? row.quantity : 0,
      Balance: row.newQuantity ?? '', 'Purchase No': row.purchaseId,
      'Purchase Date': row.purchaseDate?.slice(0, 10) ?? '', Supplier: row.supplierName ?? '',
      Farm: row.farmId ?? '', Rate: row.unitPrice ?? '', Total: row.totalAmount ?? '',
      // Purchase status is a receipt status, not a payment status.
      _raw: row,
    }
  })
  return { records, inventory }
}
export function buildMovement(screen, values, inventory) {
  const matches = inventory.filter((item) => String(item.inventoryId) === values.Product || item.itemName === values.Product)
  if (matches.length !== 1) throw new Error('Select a product from inventory. Products with the same name must be selected by their inventory ID.')
  const item = matches[0]
  const quantity = Number(values.Quantity)
  if (!Number.isFinite(quantity) || quantity <= 0) throw new Error('Quantity must be greater than zero.')
  if (!values.Date || Number.isNaN(Date.parse(values.Date))) throw new Error('Enter a valid transaction date.')
  if (screen === 'Stock Out' && quantity > item.quantity) throw new Error('Quantity exceeds the available stock.')
  const unsupported = ['Category', 'Issued To', 'Farm / Warehouse', 'Purpose', 'Approved By']
  const entered = unsupported.filter((field) => values[field]?.trim())
  if (entered.length) throw new Error(`The API cannot save these fields yet: ${entered.join(', ')}.`)
  if (values.Unit && values.Unit.toLowerCase() !== item.unit?.toLowerCase()) throw new Error(`This product uses ${item.unit}. Unit conversion is not supported by the API.`)
  if (screen === 'Stock In' && values['Source / Supplier'] && values['Source / Supplier'] !== item.supplier) throw new Error('The stock API cannot save a different supplier for this transaction.')
  return {
    inventoryId: item.inventoryId, movementType: screen === 'Stock In' ? 'StockIn' : 'StockOut',
    quantity, movementDate: `${values.Date}T00:00:00`,
    referenceNumber: values['Reference No'] || null, description: values.Remarks || null,
    createdBy: localStorage.getItem('agriman_user_name') || sessionStorage.getItem('agriman_user_name') || null,
  }
}
export async function createMovement(screen, values, inventory) {
  if (screen === 'Stock Ledger') throw new Error('The ledger is generated by stock movements. A ledger creation API is not available.')
  if (screen === 'Stock Adjustment') throw new Error('Adjustment creation needs backend confirmation: does quantity mean a signed change or the final stock count?')
  if (screen === 'Purchases') {
    const missing = ['Purchase No', 'Crop', 'Discount', 'Tax', 'Payment Status'].filter((field) => values[field]?.trim())
    if (missing.length) throw new Error(`The purchase API cannot save these fields yet: ${missing.join(', ')}.`)
    const item = inventory.find((entry) => String(entry.inventoryId) === values.Product)
    if (!item) throw new Error('Select an inventory product.')
    const quantity = Number(values.Quantity), unitPrice = Number(values.Rate)
    if (!Number.isFinite(quantity) || quantity <= 0 || !Number.isFinite(unitPrice) || unitPrice < 0) throw new Error('Enter a positive quantity and a valid non-negative rate.')
    if (!values['Purchase Date'] || Number.isNaN(Date.parse(values['Purchase Date']))) throw new Error('Enter a valid purchase date.')
    const farmId = values.Farm ? Number(values.Farm) : null
    if (farmId !== null && (!Number.isInteger(farmId) || farmId <= 0)) throw new Error('The purchase API requires a numeric farm ID. A farm lookup API is needed to select farms by name.')
    await api.post('/api/Purchases', {
      itemName: item.itemName, inventoryId: item.inventoryId, unit: item.unit,
      supplierName: values.Supplier || null, farmId, quantity, unitPrice,
      totalAmount: quantity * unitPrice, purchaseDate: `${values['Purchase Date']}T00:00:00`,
    }, options())
    return
  }
  await api.post(`/api/${routes[screen]}`, buildMovement(screen, values, inventory), options())
}
